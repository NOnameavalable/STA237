# Run from any directory: Rscript /absolute/path/to/generate_graphs.R
args <- commandArgs(trailingOnly=FALSE)
script <- sub("^--file=", "", args[grepl("^--file=", args)])
out <- file.path(dirname(normalizePath(script)), "..", "graphs")
dir.create(out, showWarnings=FALSE, recursive=TRUE)
png(file.path(out, "chebyshev.png"), width=1500, height=800, res=150)
par(mfrow=c(2,1), mar=c(4,5,2.5,2), family="sans")
plot(c(-4,4),c(0,1),type="n",axes=FALSE,xlab="Distance from the mean, in standard deviations",ylab="",main="Chebyshev: a central interval and its complementary tails")
rect(-4,.15,-2,.65,col="#f6d4c8",border=NA)
rect(-2,.15,2,.65,col="#d3e8ef",border=NA)
rect(2,.15,4,.65,col="#f6d4c8",border=NA)
axis(1,at=c(-2,0,2),labels=c(expression(mu-k*sigma),expression(mu),expression(mu+k*sigma)))
text(0,.4,expression(abs(X-mu)<k*sigma),cex=1.15)
text(-3,.4,"Left tail");text(3,.4,"Right tail")
segments(c(-2,2),.05,c(-2,2),.8,lty=2,col="#934a36",lwd=2)
text(0,.88,"Both endpoints belong to the tail event",col="#934a36")
k <- seq(.25,5,length.out=400)
plot(k,pmax(0,1-1/k^2),type="l",lwd=3,col="#1a6b87",ylim=c(0,1),xlab="k (number of standard deviations)",ylab="Guaranteed central probability",main="Distribution-free lower bound: max(0, 1 - 1/k^2)")
abline(h=c(.75,8/9),v=c(2,3),lty=3,col="#b0b7c0")
points(c(2,3),c(.75,8/9),pch=19,col="#1a6b87")
text(c(2,3),c(.75,8/9),labels=c("75%","88.89%"),pos=4,cex=.85)
dev.off()
png(file.path(out,"binomial-family.png"),width=1800,height=650,res=150)
par(mfrow=c(1,3),mar=c(4,4,4,1),family="sans")
for (pair in list(c(10,.2),c(10,.7),c(20,.7))) {
  n <- pair[1];p <- pair[2]; x <- 0:20;y <- dbinom(x,n,p)
  plot(x,y,type="n",xlim=c(-.5,20.5),ylim=c(0,.33),xlab="x (success count)",ylab="P(X = x)",main=sprintf("Bin(%d, %.1f)\nMean %.1f; SD %.3f",n,p,n*p,sqrt(n*p*(1-p))))
  rect(x-.36,0,x+.36,y,col="#48a885",border="#296b54")
  abline(v=n*p,lty=2,col="#195276",lwd=2)
}
dev.off()
